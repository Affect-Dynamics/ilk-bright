export function codeTokens(s){const raw=String(s).replace(/([a-z0-9])([A-Z])/g,'$1 $2').replace(/([A-Z])([A-Z][a-z])/g,'$1 $2').replace(/_/g,' ');return [...tokens(s),...tokens(raw)];}
export function enhancedDocs(docs){return docs.map(d=>({...d,content:codeTokens(d.content+' '+String(d.id).replace(/[_/.-]/g,' ')).join(' ')}));}
export async function discoverCapabilities(q,jev,log){const questions=Object.fromEntries(CAPABILITIES.map(([id,terms])=>[id,{type:'noul',instructions:`Would knowledge of ${terms} materially help solve the query? Judge required or useful solution capabilities, not shared vocabulary. Evaluate independently.`}]));return jev({query:q},questions,log);}
export function capabilityRank(idx,probs,excluded=[],limit=100){const selected=CAPABILITIES.filter(([id])=>Number.isFinite(probs[id])).sort((a,b)=>probs[b[0]]-probs[a[0]]).slice(0,8).filter(([id])=>probs[id]>=.55);const scores=new Map();for(const [id,terms] of selected){const rows=rank(idx,queryTerms(terms),excluded,limit);rows.forEach((r,i)=>scores.set(r.id,(scores.get(r.id)||0)+probs[id]/(20+i+1)));}return [...scores].sort((a,b)=>b[1]-a[1]||a[0].localeCompare(b[0])).slice(0,limit).map(([id,score])=>({id,score}));}
export function protectedMerge(base,channels,extra=100){const out=[...base],seen=new Set(base.map(r=>r.id));let added=0;for(let i=0;added<extra&&i<Math.max(0,...channels.map(c=>c.length));i++){for(const c of channels){const r=c[i];if(r&&!seen.has(r.id)&&added<extra){seen.add(r.id);out.push(r);added++;}}}return out;}
